# ── confidence 기준 ────────────────────────────────────────
CONFIDENCE_GUIDE = (
    "[confidence 기준]\n"
    "- 90~100: 복수의 지표가 같은 방향을 강하게 지지\n"
    "- 70~89 : 주요 지표가 방향을 지지하나 일부 불확실성 존재\n"
    "- 50~69 : 방향은 있으나 근거가 제한적\n"
    "- 50 미만: 방향을 확신할 수 없음 → 반드시 Neutral 선택"
)


def build_criteria() -> str:
    """절대 방향(주가 상승/하락) 기준 판단 텍스트 반환."""
