        "[판단 기준]\n"
        "- Buy    : 향후 20거래일 내 주가 상승 예상\n"
        "- Sell   : 향후 20거래일 내 주가 하락 예상\n"
        "- Neutral: 상승·하락 근거가 균형을 이루거나 방향성을 확신할 수 없을 때의 적극적 선택.\n"
        "           소극적 판단이 아니며, 방향이 불명확한 상황에서 올바른 결정임"
